"""
Convert paper/submit_ready.md (and review_manuscript.md for the long form) into
the LaTeX fragments used by paper/Formatting_Instructions_For_NeurIPS_2026/main_short.tex
(and main.tex). Idempotent — safe to re-run any time the markdown changes.

Outputs (short / submission form):
  _abstract_short.tex   — abstract body (no \begin{abstract} wrapper; main_short.tex wraps it)
  body_main_short.tex   — sections 1..9 of the main paper
  refs_short.tex        — references section
  body_appendix.tex     — appendices A..F + Z (extended discussion)

The pre-existing tex files were generated by an earlier pandoc run that
treated some unicode whitespace as U+00A0, producing tildes between every
word. The current markdown source has 0 nbsp, so a clean pandoc run on the
current source produces clean LaTeX.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUBMIT_MD = ROOT / "submit_ready.md"
REVIEW_MD = ROOT / "review_manuscript.md"
LATEX_DIR = ROOT / "Formatting_Instructions_For_NeurIPS_2026"


def split_md(md: str) -> dict[str, str]:
    """Split submit_ready.md into (yaml, body sections by H1)."""
    yaml_match = re.match(r"^---\n(.*?)\n---\n", md, re.DOTALL)
    yaml = yaml_match.group(1) if yaml_match else ""
    body = md[yaml_match.end():] if yaml_match else md

    # Extract abstract from YAML
    abs_match = re.search(r"^abstract:\s*\|\n((?:[ ]{2}.*\n?)+)", yaml, re.MULTILINE)
    if not abs_match:
        raise SystemExit("ERROR: no abstract: | block in YAML")
    abstract = "\n".join(line[2:] for line in abs_match.group(1).split("\n"))

    # Split body by H1
    parts = re.split(r"^(# .+)$", body, flags=re.MULTILINE)
    # parts is [pre, "# 1. ...", body1, "# 2. ...", body2, ...]
    sections: dict[str, str] = {}
    for i in range(1, len(parts), 2):
        header = parts[i]
        content = parts[i + 1] if i + 1 < len(parts) else ""
        sections[header] = content

    return {"abstract": abstract, "sections": sections}


# (last-name -> (year -> bibkey)) mapping for citation substitution.
# Year disambiguates same-author multiple-paper cases (Twinanda 2017 vs 2019,
