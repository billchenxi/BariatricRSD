"""Build an editable PowerPoint version of fig_project_overall_pipeline.

The original PNG/PDF is generated by build_fig_project_overall_pipeline.py.
This script recreates the same scientific content as native PowerPoint
objects so the diagram can be edited for talks. Real BBP12 frames remain
embedded pictures; boxes, arrows, labels, panels, and annotations are
editable shapes/text.

Output:
    paper/figures/fig_project_overall_pipeline_editable.pptx
"""
from __future__ import annotations

from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile
from xml.sax.saxutils import escape


