def build_rels() -> str:
    rels = [
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slideLayout" Target="../slideLayouts/slideLayout7.xml"/>'
    ]
    for idx in range(len(ASSETS)):
        rels.append(
            f'<Relationship Id="rId{idx + 2}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="../media/project_pipeline_frame{idx + 1}.jpeg"/>'
        )
    return (
        "<?xml version='1.0' encoding='UTF-8' standalone='yes'?>"
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        f"{''.join(rels)}</Relationships>"
    )


def update_presentation_size(xml: bytes) -> bytes:
    text = xml.decode("utf-8")
    text = text.replace(
        '<p:sldSz cx="12188952" cy="6858000" type="screen4x3"/>',
        f'<p:sldSz cx="{emu(SLIDE_W)}" cy="{emu(SLIDE_H)}" type="custom"/>',
    )
    return text.encode("utf-8")


def main() -> None:
    missing = [str(p) for p in ASSETS if not p.exists()]
    if missing:
        raise FileNotFoundError(f"Missing frame assets: {missing}")

    slide_xml = build_slide_xml().encode("utf-8")
    rels_xml = build_rels().encode("utf-8")
    OUT.parent.mkdir(parents=True, exist_ok=True)

    with ZipFile(TEMPLATE, "r") as zin, ZipFile(OUT, "w", ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            if item.filename in {"ppt/slides/slide1.xml", "ppt/slides/_rels/slide1.xml.rels"}:
                continue
            data = zin.read(item.filename)
            if item.filename == "ppt/presentation.xml":
                data = update_presentation_size(data)
            zout.writestr(item, data)
        zout.writestr("ppt/slides/slide1.xml", slide_xml)
        zout.writestr("ppt/slides/_rels/slide1.xml.rels", rels_xml)
        for idx, asset in enumerate(ASSETS, start=1):
            zout.writestr(f"ppt/media/project_pipeline_frame{idx}.jpeg", asset.read_bytes())

    print(OUT)


if __name__ == "__main__":
    main()
