def asset_path(name: str) -> Path:
    local = LAMBDA_FRAME_DIR / name
    if local.exists():
        return local
    return SLIDE_ASSET_DIR / name


ASSETS = [asset_path(name) for name in FRAME_NAMES]


def emu(value_in: float) -> str:
    return str(int(round(value_in * EMU_PER_IN)))


def font_size(pt: float) -> str:
    return str(int(round(pt * 100)))


def next_id() -> int:
    global shape_id
    shape_id += 1
    return shape_id


def fill_xml(color: str | None) -> str:
    if color is None:
        return "<a:noFill/>"
    return f'<a:solidFill><a:srgbClr val="{color}"/></a:solidFill>'


def line_xml(
    color: str = COLORS["edge"],
    width_pt: float = 1.0,
    dash: str | None = None,
    no_line: bool = False,
    arrow: bool = False,
) -> str:
    if no_line:
        return "<a:ln><a:noFill/></a:ln>"
    dash_xml = f'<a:prstDash val="{dash}"/>' if dash else ""
    arrow_xml = '<a:tailEnd type="triangle" w="med" h="med"/>' if arrow else ""
    width = int(round(width_pt * 12_700))
    return (
        f'<a:ln w="{width}">'
        f'<a:solidFill><a:srgbClr val="{color}"/></a:solidFill>'
        f"{dash_xml}{arrow_xml}</a:ln>"
    )


def text_body(
    text: str | list[str],
    font_pt: float = 10,
    color: str = COLORS["ink"],
    bold: bool = False,
    align: str = "ctr",
    anchor: str = "ctr",
) -> str:
    lines = text.split("\n") if isinstance(text, str) else text
    bold_flag = "1" if bold else "0"
    paragraphs = []
    for line in lines:
        paragraphs.append(
            f'<a:p><a:pPr algn="{align}"/>'
            f'<a:r><a:rPr sz="{font_size(font_pt)}" b="{bold_flag}">'
            f'<a:solidFill><a:srgbClr val="{color}"/></a:solidFill>'
            f'<a:latin typeface="Arial"/></a:rPr>'
            f"<a:t>{escape(line)}</a:t></a:r></a:p>"
        )
    return (
        f'<p:txBody><a:bodyPr wrap="square" anchor="{anchor}" '
        'lIns="0" rIns="0" tIns="0" bIns="0"><a:spAutoFit/></a:bodyPr>'
        f"<a:lstStyle/>{''.join(paragraphs)}</p:txBody>"
    )


def shape(
    name: str,
    prst: str,
    x: float,
    y: float,
    w: float,
    h: float,
    fill: str | None = None,
    stroke: str = COLORS["edge"],
    stroke_pt: float = 0.9,
    text: str | list[str] | None = None,
    font_pt: float = 10,
    text_color: str = COLORS["ink"],
    bold: bool = False,
    align: str = "ctr",
    anchor: str = "ctr",
    no_line: bool = False,
    dash: str | None = None,
) -> None:
    sid = next_id()
    body = (
        text_body(text, font_pt, text_color, bold, align, anchor)
        if text is not None
        else '<p:txBody><a:bodyPr rtlCol="0" anchor="ctr"/><a:lstStyle/><a:p/></p:txBody>'
    )
    parts.append(
        f'<p:sp><p:nvSpPr><p:cNvPr id="{sid}" name="{escape(name)}"/>'
        f"<p:cNvSpPr/><p:nvPr/></p:nvSpPr><p:spPr>"
        f'<a:xfrm><a:off x="{emu(x)}" y="{emu(y)}"/>'
        f'<a:ext cx="{emu(w)}" cy="{emu(h)}"/></a:xfrm>'
        f'<a:prstGeom prst="{prst}"><a:avLst/></a:prstGeom>'
        f"{fill_xml(fill)}{line_xml(stroke, stroke_pt, dash=dash, no_line=no_line)}"
        f"</p:spPr>{body}</p:sp>"
    )


def textbox(
    name: str,
    x: float,
    y: float,
    w: float,
    h: float,
    text: str | list[str],
    font_pt: float = 10,
    color: str = COLORS["ink"],
    bold: bool = False,
    align: str = "l",
) -> None:
    sid = next_id()
    parts.append(
        f'<p:sp><p:nvSpPr><p:cNvPr id="{sid}" name="{escape(name)}"/>'
        f'<p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr><p:spPr>'
        f'<a:xfrm><a:off x="{emu(x)}" y="{emu(y)}"/>'
        f'<a:ext cx="{emu(w)}" cy="{emu(h)}"/></a:xfrm>'
        '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/></p:spPr>'
        f"{text_body(text, font_pt, color, bold, align)}</p:sp>"
    )


def line(
    name: str,
    x1: float,
    y1: float,
    x2: float,
    y2: float,
    color: str = COLORS["edge"],
    width_pt: float = 1.15,
    arrow: bool = False,
    dash: str | None = None,
) -> None:
    sid = next_id()
    flip_h = x2 < x1
    flip_v = y2 < y1
    x = min(x1, x2)
    y = min(y1, y2)
    w = abs(x2 - x1)
    h = abs(y2 - y1)
    flips = ""
    if flip_h:
        flips += ' flipH="1"'
    if flip_v:
        flips += ' flipV="1"'
    parts.append(
        f'<p:cxnSp><p:nvCxnSpPr><p:cNvPr id="{sid}" name="{escape(name)}"/>'
        f"<p:cNvCxnSpPr/><p:nvPr/></p:nvCxnSpPr><p:spPr>"
        f'<a:xfrm{flips}><a:off x="{emu(x)}" y="{emu(y)}"/>'
        f'<a:ext cx="{emu(w)}" cy="{emu(h)}"/></a:xfrm>'
        '<a:prstGeom prst="line"><a:avLst/></a:prstGeom>'
        f"{line_xml(color, width_pt, dash=dash, arrow=arrow)}</p:spPr></p:cxnSp>"
    )


def arrow(x1: float, y1: float, x2: float, y2: float, color: str = COLORS["edge"], dash: bool = False) -> None:
    line("Arrow", x1, y1, x2, y2, color, 1.1, True, "dash" if dash else None)


def picture(name: str, rid: str, x: float, y: float, w: float, h: float, crop_tb: int = 0) -> None:
    sid = next_id()
    crop = f'<a:srcRect t="{crop_tb}" b="{crop_tb}"/>' if crop_tb else ""
    parts.append(
        f'<p:pic><p:nvPicPr><p:cNvPr id="{sid}" name="{escape(name)}"/>'
        '<p:cNvPicPr><a:picLocks noChangeAspect="1"/></p:cNvPicPr><p:nvPr/></p:nvPicPr>'
        f'<p:blipFill><a:blip r:embed="{rid}"/>{crop}'
        '<a:stretch><a:fillRect/></a:stretch></p:blipFill><p:spPr>'
        f'<a:xfrm><a:off x="{emu(x)}" y="{emu(y)}"/>'
        f'<a:ext cx="{emu(w)}" cy="{emu(h)}"/></a:xfrm>'
        '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr></p:pic>'
    )


def block(x: float, y: float, w: float, h: float, text: str, fill: str, stroke: str, font_pt: float = 8.2) -> None:
    shape("Block", "roundRect", x, y, w, h, fill, stroke, 1.0, text, font_pt, COLORS["ink"], True)


def panel_label(x: float, y: float, text: str) -> None:
    textbox("Panel label", x, y, 4.8, 0.22, text, 10.3, COLORS["ink"], True)


def filmstrip(x: float, y: float, w: float, h: float) -> None:
    shape("Filmstrip", "rect", x, y, w, h, "0B0F19", "000000", 0.8)
    for i in range(9):
        yy = y + 0.12 + i * (h - 0.28) / 8
        shape("Film hole left", "rect", x + 0.04, yy, 0.06, 0.05, "FFFFFF", "FFFFFF", 0.1)
        shape("Film hole right", "rect", x + w - 0.10, yy, 0.06, 0.05, "FFFFFF", "FFFFFF", 0.1)
    img_h = 0.19
    for i in range(8):
        yy = y + 0.14 + i * (img_h + 0.045)
        picture(f"Film frame {i + 1}", f"rId{i + 2}", x + 0.15, yy, w - 0.30, img_h, crop_tb=7000)
    textbox("Time label", x + 0.18, y + h + 0.05, w - 0.36, 0.16, "time", 6.8, COLORS["muted"], False, "ctr")
    arrow(x + w / 2, y + h + 0.20, x + w / 2, y + h + 0.48, COLORS["ink"])


def clip_stack(x: float, y: float, w: float, h: float) -> None:
    shape("Clip outline", "roundRect", x, y, w, h, None, COLORS["blue"], 1.0, dash="dash")
    img_h = 0.17
    for i in range(8):
        yy = y + 0.14 + i * (img_h + 0.035)
        picture(f"Clip frame {i + 1}", f"rId{i + 2}", x + 0.12, yy, w - 0.24, img_h, crop_tb=7000)
    textbox("Clip label", x - 0.05, y + h + 0.04, w + 0.10, 0.18, "8-frame clip", 7.8, COLORS["blue"], True, "ctr")


def feature_matrix(x: float, y: float, w: float, h: float) -> None:
    shape("Feature matrix", "rect", x, y, w, h, COLORS["blue_light"], COLORS["blue"], 0.9)
    for i in range(1, 8):
        yy = y + i * h / 8
        line("Matrix row", x, yy, x + w, yy, "BFDBFE", 0.45)
    for r in range(8):
        yy = y + (r + 0.5) * h / 8
        textbox("row label", x - 0.24, yy - 0.05, 0.18, 0.10, f"t_{r + 1}", 5.8, COLORS["ink"], False, "r")
        for c in range(5):
            xx = x + 0.12 + c * (w - 0.24) / 4
            shape("Feature dot", "ellipse", xx - 0.025, yy - 0.025, 0.05, 0.05, COLORS["blue"], COLORS["blue"], 0.1)
    textbox("Tensor label", x - 0.25, y - 0.30, w + 0.50, 0.18, "8 x 768 frame tensor", 7.6, COLORS["blue"], True, "ctr")
    textbox("768 label", x + 0.22, y + h + 0.03, w - 0.44, 0.12, "768", 6.4, COLORS["muted"], False, "ctr")


def phase_sequence(x: float, y: float, w: float, h: float) -> None:
    phases = [("P1", "2563EB"), ("P2", "0F766E"), ("P3", "D97706"), ("P2", "0F766E"), ("P4", "7C3AED"), ("P5", "DB2777")]
    gap = 0.03
    seg_w = (w - gap * (len(phases) - 1)) / len(phases)
    for i, (label, color) in enumerate(phases):
        xx = x + i * (seg_w + gap)
        shape("Phase segment", "rect", xx, y, seg_w, h, color, "FFFFFF", 0.3, label, 5.8, "FFFFFF", True)


